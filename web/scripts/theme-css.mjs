// Writes OpenUI's theme tokens as static CSS. ThemeProvider injects a <style>
// element at runtime, which the console's style-src 'self' policy refuses.
import {createRequire} from 'node:module';
import {writeFileSync} from 'node:fs';

const require = createRequire(import.meta.url);
const {defaultDarkTheme, defaultLightTheme} = require('../node_modules/@openuidev/react-ui/dist/components/ThemeProvider/index.cjs');
// Same naming as OpenUI's themeToCssVars, which the package does not export.
const kebab = key => key.replace(/([a-z])([A-Z])/g, '$1-$2').replace(/([A-Z])([A-Z])/g, '$1-$2').replace(/([a-z])(\d)/g, '$1-$2').toLowerCase();
const vars = (theme, indent) => Object.entries(theme).filter(([, value]) => typeof value === 'string').map(([key, value]) => `${indent}--openui-${kebab(key)}: ${value};`).join('\n');

writeFileSync(new URL('../src/theme.css', import.meta.url), `/* Generated by scripts/theme-css.mjs from @openuidev/react-ui. Do not edit. */
:root {
  color-scheme: light;
${vars(defaultLightTheme, '  ')}
}
@media (prefers-color-scheme: dark) {
  :root {
    color-scheme: dark;
${vars(defaultDarkTheme, '    ')}
  }
}
`);
